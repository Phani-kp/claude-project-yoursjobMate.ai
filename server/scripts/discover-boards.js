// Finds which companies in scripts/company-candidates.txt have a public careers feed on Greenhouse, Lever or Ashby,
// and writes the ones that really exist and list US jobs to src/moreCompanies.js. Nothing is added on a guess:
// a company is kept only when its feed answered and returned at least one US job.
//
//   node scripts/discover-boards.js            check the candidates and rewrite src/moreCompanies.js
//   node scripts/discover-boards.js --dry-run  check and print, without writing
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

process.env.DB_PATH ||= ':memory:';
const here = path.dirname(fileURLToPath(import.meta.url));
const { ATS } = await import('../src/sources.js');
const { COMPANY_BOARDS } = await import('../src/companies.js');
let previous = {};
try { previous = (await import('../src/moreCompanies.js')).MORE_COMPANY_BOARDS; } catch { /* first run */ }

const PLATFORMS = ['greenhouse', 'ashby', 'lever'];
const slug = (name) => name.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]/g, '');
const candidates = readFileSync(path.join(here, 'company-candidates.txt'), 'utf8').split('\n')
  .map((line) => line.trim()).filter((line) => line && !line.startsWith('#'))
  .map((line) => { const [name, token] = line.split('='); return { name: name.trim(), token: (token || slug(name)).trim() }; });

const builtIn = new Set(Object.entries(COMPANY_BOARDS).flatMap(([ats, list]) => Object.keys(list).map((token) => `${ats}:${token.toLowerCase()}`)));
const builtInNames = new Set(Object.values(COMPANY_BOARDS).flatMap((list) => Object.values(list).map((name) => name.toLowerCase())));
const found = Object.fromEntries(PLATFORMS.map((ats) => [ats, {}]));
const stats = { checked: 0, kept: 0, alreadyBuiltIn: 0, notFound: 0 };

let next = 0;
async function worker() {
  while (next < candidates.length) {
    const { name, token } = candidates[next++];
    stats.checked++;
    if (builtInNames.has(name.toLowerCase()) || PLATFORMS.some((ats) => builtIn.has(`${ats}:${token}`))) { stats.alreadyBuiltIn++; continue; }
    let kept = false;
    // One feed per company: the first platform that answers with US jobs.
    for (const ats of PLATFORMS) {
      try {
        const jobs = (await ATS[ats]({ token, name })).filter((job) => job.us);
        if (!jobs.length) continue;
        found[ats][token] = name;
        kept = true;
        console.log(`  + ${name}: ${ats}:${token} (${jobs.length} US jobs)`);
        break;
      } catch { /* no feed with this token on this platform */ }
    }
    kept ? stats.kept++ : stats.notFound++;
  }
}
await Promise.all(Array.from({ length: 10 }, worker));

// Boards verified on an earlier run stay unless they are now built in, so a network hiccup never shrinks the list.
for (const ats of PLATFORMS) {
  for (const [token, name] of Object.entries(previous[ats] || {})) {
    if (!builtIn.has(`${ats}:${token}`) && !PLATFORMS.some((other) => found[other][token])) found[ats][token] = name;
  }
}
const total = PLATFORMS.reduce((sum, ats) => sum + Object.keys(found[ats]).length, 0);
console.log(`\nChecked ${stats.checked}: ${stats.kept} verified now, ${stats.alreadyBuiltIn} already built in, ${stats.notFound} without a feed. List now has ${total} companies.`);

if (!process.argv.includes('--dry-run')) {
  const body = PLATFORMS.map((ats) => `  ${ats}: {\n${Object.entries(found[ats]).sort(([, a], [, b]) => a.localeCompare(b))
    .map(([token, name]) => `    ${JSON.stringify(token)}: ${JSON.stringify(name)},`).join('\n')}\n  },`).join('\n');
  writeFileSync(path.join(here, '../src/moreCompanies.js'), `// Generated by scripts/discover-boards.js. Do not edit by hand: add names to scripts/company-candidates.txt and re-run.
// Every company here had a live careers feed with US jobs when it was last checked.
export const MORE_COMPANY_BOARDS = {
${body}
};
`);
  console.log('Wrote src/moreCompanies.js');
}
process.exit(0);
